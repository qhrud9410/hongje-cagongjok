export function parseCsOutput(text: string) {
  const pick = (tag: string) => {
    const m = text.match(new RegExp(`<${tag}>([\\s\\S]*?)(?:</${tag}>|$)`));
    return m ? m[1].trim() : "";
  };
  let reply = pick("reply"), memo = pick("memo");
  const checks = pick("check").split("\n").map((x) => x.replace(/^\s*(?:[-•*]|\d+[.)])\s*/, "").trim()).filter((x) => x.length > 1).slice(0, 6);
  if (!reply && !memo) reply = text.trim();
  return { reply, memo, checks };
}
