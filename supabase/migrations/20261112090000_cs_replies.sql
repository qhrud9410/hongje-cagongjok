-- CS 관리: 고객 문의와 AI 답장 초안 기록. 바깥에서는 직접 못 읽고 서버 함수(service_role)로만 다룬다.
begin;

create table if not exists public.cs_replies (
  rid bigint generated by default as identity primary key,
  id text not null unique,
  at text not null default '',
  date text not null default '',
  mid text not null default '',
  name text not null default '',
  question text not null default '' check (length(question) <= 4000),
  reply text not null default '',
  memo text not null default '',
  extra text not null default '',
  model text not null default '',
  parent text not null default ''
);
create index if not exists cs_replies_date on public.cs_replies (date);

alter table public.cs_replies enable row level security;
revoke all on public.cs_replies from public, anon, authenticated;
grant select, insert, update, delete on public.cs_replies to service_role;
grant usage, select on sequence public.cs_replies_rid_seq to service_role;

-- 다른 표와 같이 열려 있는 화면에 '바뀌었음' 신호만 보낸다
drop trigger if exists sync_cs_replies on public.cs_replies;
create trigger sync_cs_replies after insert or update or delete on public.cs_replies
  for each statement execute function public.notify_change();

commit;
