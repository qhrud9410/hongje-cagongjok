-- 매출·비용 장부 (점주 전용). 바깥에서는 직접 못 읽고, 서버 함수(service_role)로만 다룬다.
-- 고정비 초깃값 같은 실제 금액은 이 파일에 넣지 않는다 (저장소가 공개라서).
begin;

create table if not exists public.finance_tx (
  rid bigint generated by default as identity primary key,
  id text not null unique,
  date text not null check (date ~ '^20\d{2}-\d{2}-\d{2}$'),
  kind text not null check (kind in ('sale','refund','expense','expenseRefund','transfer','review')),
  source text not null check (source in ('manual','toss','hyundai','kb')),
  name text not null check (length(name) between 1 and 200),
  amount bigint not null check (amount >= 0 and amount <= 10000000000),
  category text not null default '기타',
  "externalId" text not null default '',
  note text not null default '',
  "createdAt" text not null default '',
  "updatedAt" text not null default '',
  by text not null default '',
  check (source <> 'kb' or kind in ('transfer','review'))
);
create index if not exists finance_tx_date on public.finance_tx (date);
create unique index if not exists finance_tx_ext on public.finance_tx (source, "externalId") where "externalId" <> '';

-- 월별 설정. ym = 'YYYY-MM', 또는 새 달의 초깃값으로 쓰는 'default'
create table if not exists public.finance_month (
  ym text primary key check (ym = 'default' or ym ~ '^20\d{2}-(0[1-9]|1[0-2])$'),
  fixed jsonb not null default '[]'::jsonb check (jsonb_typeof(fixed) = 'array'),
  "royaltyRate" numeric not null default 0 check ("royaltyRate" >= 0 and "royaltyRate" <= 100),
  confirmed boolean not null default false,
  "excludedPurchases" jsonb not null default '[]'::jsonb check (jsonb_typeof("excludedPurchases") = 'array'),
  "updatedAt" text not null default ''
);

alter table public.finance_tx enable row level security;
alter table public.finance_month enable row level security;
revoke all on public.finance_tx, public.finance_month from public, anon, authenticated;
grant select, insert, update, delete on public.finance_tx, public.finance_month to service_role;
grant usage, select on sequence public.finance_tx_rid_seq to service_role;

-- 다른 표와 같은 방식으로 열려 있는 화면에 '바뀌었음' 신호만 보낸다 (내용은 안 보냄)
drop trigger if exists sync_finance_tx on public.finance_tx;
create trigger sync_finance_tx after insert or update or delete on public.finance_tx
  for each statement execute function public.notify_change();
drop trigger if exists sync_finance_month on public.finance_month;
create trigger sync_finance_month after insert or update or delete on public.finance_month
  for each statement execute function public.notify_change();

commit;
